import fs from 'node:fs';
import path from 'node:path';

const responseDir = path.resolve('scripts/demo_responses');
const cases = ['good', 'mediocre', 'unrelated'];
const manifest = JSON.parse(fs.readFileSync(path.join(responseDir, 'manifest.json'), 'utf8'));
if (manifest.generated_by !== 'scripts/demo_check.py') {
  throw new Error('demo response manifest was not generated by demo_check.py');
}

for (const name of cases) {
  const file = path.join(responseDir, `${name}.json`);
  if (!fs.existsSync(file) || !manifest.sha256?.[name]) {
    throw new Error(`${name}: response file or manifest entry is missing`);
  }
  const actualHash = await import('node:crypto').then(({ createHash }) =>
    createHash('sha256').update(fs.readFileSync(file)).digest('hex'));
  if (actualHash !== manifest.sha256[name]) {
    throw new Error(`${name}: response was not generated by the recorded demo run`);
  }
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const field of ['matched_skills', 'missing_skills', 'related_skills']) {
    if (!Array.isArray(data[field])) throw new Error(`${name}: missing ${field}`);
  }
  const counts = {
    matched: data.matched_skills.length,
    missing: data.missing_skills.length,
    related: data.related_skills.length,
  };
  console.log(`${name}: matched=${counts.matched} missing=${counts.missing} related=${counts.related}`);
}
console.log('PASS: frontend skill counts match saved /api/analyze responses');
