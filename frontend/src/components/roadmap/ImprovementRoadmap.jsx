import React from 'react';
import { motion } from 'framer-motion';
import { BookOpen, Video, Code, BrainCircuit, Loader2 } from 'lucide-react';

const ImprovementRoadmap = ({ roadmapData, isLoading }) => {
  const isRuleBased = roadmapData?.provider === 'rule-based';
  const providerLabel = isRuleBased ? 'Rule-Based Engine' : roadmapData?.provider || 'AI Engine';
  
  const getIcon = (type) => {
    switch (type) {
      case 'course': return <Video className="w-4 h-4" />;
      case 'project': return <Code className="w-4 h-4" />;
      case 'reading': return <BookOpen className="w-4 h-4" />;
      default: return <BrainCircuit className="w-4 h-4" />;
    }
  };

  const getDifficultyColor = (diff) => {
    if (diff === 'Beginner') return 'text-green-400 bg-green-400/10 border-green-400/20';
    if (diff === 'Intermediate') return 'text-yellow-400 bg-yellow-400/10 border-yellow-400/20';
    return 'text-red-400 bg-red-400/10 border-red-400/20';
  };

  if (isLoading) {
    return (
      <div className="p-8 flex flex-col items-center justify-center text-gray-400 min-h-[400px] bg-[#0a0a1a]/80 backdrop-blur-xl border border-white/10 rounded-2xl">
        <Loader2 className="w-12 h-12 animate-spin text-indigo-500 mb-4" />
        <p className="font-['Outfit'] text-lg">AI is generating your personalized learning roadmap...</p>
      </div>
    );
  }

  if (!roadmapData || !roadmapData.milestones) return null;

  return (
    <div className="bg-[#0a0a1a]/80 backdrop-blur-xl border border-white/10 rounded-2xl p-6 text-white font-['Inter'] shadow-xl relative overflow-hidden">
      <div className="absolute top-0 right-0 bg-white/5 border-b border-l border-white/10 px-4 py-1.5 rounded-bl-xl text-xs flex items-center gap-2">
        <span className="text-gray-400">Generated by:</span>
        <span className={`w-2 h-2 rounded-full ${isRuleBased ? 'bg-orange-500' : 'bg-indigo-500'}`}></span>
        <span className="font-semibold">{providerLabel}</span>
      </div>

      <h2 className="text-2xl font-bold font-['Outfit'] mb-8 mt-2">Improvement Roadmap</h2>
      
      <div className="relative border-l border-white/10 ml-4 space-y-8 pb-4">
        {roadmapData.milestones.map((milestone, idx) => (
          <motion.div 
            key={idx}
            initial={{ opacity: 0, x: -20 }}
            animate={{ opacity: 1, x: 0 }}
            transition={{ delay: idx * 0.2 }}
            className="relative pl-8"
          >
            <div className="absolute -left-2 top-1.5 w-4 h-4 rounded-full bg-[#0a0a1a] border-2 border-indigo-500" />
            
            <h3 className="text-xl font-['Outfit'] font-semibold text-indigo-300 mb-4">
              {milestone.timeframe} <span className="text-gray-400 text-base font-normal ml-2">- {milestone.focus}</span>
            </h3>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {milestone.skills.map((skill, sIdx) => (
                <div key={sIdx} className="bg-white/5 border border-white/10 rounded-xl p-4 hover:bg-white/10 transition-colors">
                  <div className="flex justify-between items-start mb-2">
                    <h4 className="font-semibold text-gray-200">{skill.name}</h4>
                    <span className={`text-[10px] px-2 py-0.5 rounded-full border ${getDifficultyColor(skill.difficulty)}`}>
                      {skill.difficulty}
                    </span>
                  </div>
                  <p className="text-sm text-gray-400 mb-3 line-clamp-2">{skill.description}</p>
                  
                  <div className="flex items-center justify-between mt-auto">
                    <span className="text-xs text-gray-500 flex items-center gap-1">
                      {getIcon(skill.type)} {skill.estimatedHours} hrs
                    </span>
                    {skill.resourceLink && (
                      <a href={skill.resourceLink} target="_blank" rel="noreferrer" className="text-xs text-indigo-400 hover:text-indigo-300 transition-colors">
                        View Resource
                      </a>
                    )}
                  </div>
                </div>
              ))}
            </div>
          </motion.div>
        ))}
      </div>

      <div className="mt-8 pt-6 border-t border-white/10 text-center">
        <p className="text-sm text-gray-400">Track your progress regularly to update your competency profile.</p>
        <button className="mt-4 px-6 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg font-medium transition-colors">
          Start Learning Journey
        </button>
      </div>
    </div>
  );
};

export default ImprovementRoadmap;
